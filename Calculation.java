public class Calculation {
    public static void main(String[] args) {
        int a = 10;
		int b = 20;
        int sum = a + b;
        int difference = a - b;
        int product = a * b;
        System.out.println("Sum: " + sum);
        System.out.println("Difference: " + difference);
        System.out.println("Product: " + product);
    }
}